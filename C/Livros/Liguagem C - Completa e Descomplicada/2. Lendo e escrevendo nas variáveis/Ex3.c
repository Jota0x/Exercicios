// Escreva um programa que leia um número inteiro e depois imprima a mensagem
// “Valor lido:”, seguido do valor inteiro. Use apenas um comando printf().
#include <stdio.h>

int main()
{
    int X;

    scanf("%d", &X); // le inteiro

    printf("Valor lido: %d", X); // imprime inteiro

    return 0;
} // end main