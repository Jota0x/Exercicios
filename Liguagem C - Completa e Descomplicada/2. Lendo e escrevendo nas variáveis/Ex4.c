// Faça um programa que leia um número inteiro e depois o imprima usando o ope-
// rador “%f”. Veja o que aconteceu.
#include <stdio.h>

int main()
{
    int X;

    scanf("%d", &X);// le inteiro 

    printf("Valor lido: %f", X);// imprime real

    return 0;

} // end main

//Resultado: ao ler inteiro e imprimir real o valor da variavel é 0